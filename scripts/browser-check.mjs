import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, channel:'chromium', args:['--disable-dev-shm-usage','--no-zygote','--single-process','--disable-gpu']});
const page = await browser.newPage({viewport:{width:1280,height:800}});
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.waitForTimeout(500);
await page.screenshot({path:'artifacts/browser-initial.png'});
const before=await page.locator('canvas').evaluate(c=>c.toDataURL());
await page.mouse.move(870,400); await page.mouse.wheel(0,1440); await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/browser-zoom-out.png'});
assert.notEqual(await page.locator('canvas').evaluate(c=>c.toDataURL()),before);
await page.locator('#start').fill('123456789012345678901234567890');
await page.locator('#start-form button').click();
await page.waitForTimeout(200);
await page.screenshot({path:'artifacts/browser-large-start.png'});
assert.equal(await page.locator('#start').inputValue(),'123456789012345678901234567890');
await page.goto('http://localhost:5173/#start=1000000&scale=10^0');
await page.reload();
await page.waitForTimeout(300);
await page.screenshot({path:'artifacts/browser-one-pixel.png'});
const runs=await page.locator('canvas').evaluate(c=>{
 const ctx=c.getContext('2d'),p=ctx.getImageData(0,0,c.width,c.height).data;
 let changes=0; for(let x=0;x<c.width;x++){let count=0;for(let y=100;y<700;y++)if(p[(y*c.width+x)*4]!==p[((y-1)*c.width+x)*4])count++;changes=Math.max(changes,count);}return changes;
});
assert.ok(runs>500,`Expected one-pixel alternating rows, got ${runs} changes`);
await page.setViewportSize({width:390,height:844});
await page.reload(); await page.waitForTimeout(200);
await page.screenshot({path:'artifacts/browser-mobile.png'});
assert.deepEqual(errors,[]);
console.log('Browser checks passed; one-pixel row transitions:',runs);
await browser.close();
